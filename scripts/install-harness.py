"""Set up this folder for one AI assistant ("harness").

Copies the coach's commands from coach/skills/ and the Garmin server from
coach/mcp.json into the files the chosen assistant reads, merging into any
existing settings without touching other entries. Files it changes are
backed up first. AGENTS.md is the shared rules file and is never written.

Run:  uv run scripts/install-harness.py <name> [--dry-run] [--uvx PATH]
      uv run scripts/install-harness.py --list
"""

import argparse
import json
import os
import platform
import re
import shutil
import sys
import time
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COACH = ROOT / "coach"
HOME = Path.home()
IS_WIN = platform.system() == "Windows"
GENERATED = ("<!-- Generated by scripts/install-harness.py from coach/. "
             "Edit coach/ and re-run instead of changing this file. -->")


class Plan:
    """Collects writes so --dry-run can show them without touching disk."""

    def __init__(self, dry: bool):
        self.dry = dry
        self.stamp = time.strftime("%Y%m%d-%H%M%S")
        self.next: list[str] = []

    def write(self, path: Path, text: str) -> None:
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old == text:
            print(f"UNCHANGED: {path}")
            return
        if self.dry:
            print(f"WOULD WRITE: {path}")
            return
        path.parent.mkdir(parents=True, exist_ok=True)
        if old is not None and not _inside_root(path):
            # Settings outside this folder belong to the athlete's apps.
            backup = path.with_name(f"{path.name}.bak-{self.stamp}")
            shutil.copy2(path, backup)
            print(f"BACKUP: {backup}")
        path.write_text(text, encoding="utf-8")
        print(f"WROTE: {path}")


def _inside_root(path: Path) -> bool:
    try:
        path.resolve().relative_to(ROOT)
        return True
    except ValueError:
        return False


def load_server() -> dict:
    return json.loads((COACH / "mcp.json").read_text(encoding="utf-8"))


def find_uvx(override: str | None) -> str:
    if override:
        return str(Path(override).expanduser())
    found = shutil.which("uvx")
    if found:
        return found
    exe = "uvx.exe" if IS_WIN else "uvx"
    for p in (HOME / ".local" / "bin" / exe, HOME / ".cargo" / "bin" / exe):
        if p.exists():
            return str(p)
    sys.exit("ERROR: can't find uvx. Install uv first (SETUP.md step 2), "
             "or pass --uvx with its full path.")


def stdio_entry(server: dict, uvx: str, typed: bool = True) -> dict:
    entry = {"type": "stdio"} if typed else {}
    entry.update(command=uvx, args=server["args"], env=server["env"])
    return entry


def read_json(path: Path) -> dict:
    if not path.exists() or not path.read_text(encoding="utf-8").strip():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        sys.exit(f"ERROR: {path} isn't valid JSON, so it wasn't changed. "
                 "Fix or remove it, then re-run.")


def dump_json(data: dict) -> str:
    return json.dumps(data, indent=2) + "\n"


def merge_server(path: Path, key: str, name: str, entry: dict) -> str:
    data = read_json(path)
    data.setdefault(key, {})[name] = entry
    return dump_json(data)


def copy_skills(plan: Plan, dest: Path) -> None:
    for src in sorted((COACH / "skills").glob("*/SKILL.md")):
        text = src.read_text(encoding="utf-8")
        # The note goes after the frontmatter, which must stay first.
        m = re.match(r"(---\n.*?\n---\n)", text, re.S)
        head, body = (m.group(1), text[m.end():]) if m else ("", text)
        out = f"{head}{GENERATED}\n{body}"
        plan.write(dest / src.parent.name / "SKILL.md", out)


# --- one function per harness -------------------------------------------

def claude_code(plan: Plan, server: dict, uvx: str) -> None:
    name = server["name"]
    # CLAUDE.md wins over AGENTS.md when both exist, so import it.
    plan.write(ROOT / "CLAUDE.md", f"{GENERATED}\n@AGENTS.md\n")
    copy_skills(plan, ROOT / ".claude" / "skills")
    mcp = ROOT / ".mcp.json"
    plan.write(mcp, merge_server(mcp, "mcpServers", name,
                                 stdio_entry(server, uvx)))
    settings = ROOT / ".claude" / "settings.json"
    data = read_json(settings)
    allow = data.setdefault("permissions", {}).setdefault("allow", [])
    for tool in server["readOnlyTools"]:
        rule = f"mcp__{name}__{tool}"
        if rule not in allow:
            allow.append(rule)
    plan.write(settings, dump_json(data))
    plan.next += [
        "Start a new Claude Code session in this folder so it loads the "
        f"'{name}' server, and approve it when asked.",
        "In the new session, type /setup to continue where setup left off.",
    ]


def cline_settings_files() -> list[Path]:
    # ~/.cline is shared by Cline's IDE, CLI and desktop app; older VS Code
    # builds keep their own copy in the extension's storage.
    files = [HOME / ".cline" / "data" / "settings" / "cline_mcp_settings.json"]
    if env := os.getenv("CLINE_MCP_SETTINGS_PATH"):
        files.insert(0, Path(env).expanduser())
    if IS_WIN:
        code = Path(os.getenv("APPDATA", HOME)) / "Code" / "User"
    elif platform.system() == "Darwin":
        code = HOME / "Library" / "Application Support" / "Code" / "User"
    else:
        code = HOME / ".config" / "Code" / "User"
    legacy = (code / "globalStorage" / "saoudrizwan.claude-dev" / "settings"
              / "cline_mcp_settings.json")
    if legacy.exists():
        files.append(legacy)
    return files


def cline(plan: Plan, server: dict, uvx: str) -> None:
    copy_skills(plan, ROOT / ".cline" / "skills")
    entry = stdio_entry(server, uvx)
    entry.update(disabled=False, autoApprove=server["readOnlyTools"])
    for path in cline_settings_files():
        plan.write(path, merge_server(path, "mcpServers", server["name"],
                                      entry))
    plan.next += [
        f"Open Cline's MCP Servers panel and check '{server['name']}' shows "
        "as connected. The first start can take a minute while uv "
        "downloads it.",
        "Send another message in the same Cline task so it picks up the "
        "new tools, then continue setup.",
    ]


def toml_str(value) -> str:
    # JSON string escaping is valid TOML basic-string escaping.
    if isinstance(value, list):
        return "[" + ", ".join(toml_str(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{json.dumps(k)} = {toml_str(v)}"
                                for k, v in value.items()) + " }"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return json.dumps(value)


def replace_toml_tables(text: str, prefix: str, block: str) -> str:
    """Drop every table under `prefix` and append `block` in their place."""
    kept, skipping = [], False
    for line in text.splitlines():
        header = re.match(r"\s*\[\[?\s*([^\]]+?)\s*\]\]?\s*(#.*)?$", line)
        if header:
            key = header.group(1).replace('"', "")
            skipping = key == prefix or key.startswith(prefix + ".")
        if not skipping:
            kept.append(line)
    body = "\n".join(kept).rstrip()
    return (body + "\n\n" if body else "") + block


def codex(plan: Plan, server: dict, uvx: str) -> None:
    name = server["name"]
    copy_skills(plan, ROOT / ".agents" / "skills")
    # User-level config: project .codex/config.toml only loads in trusted
    # projects, and a non-developer won't know to trust this folder.
    path = HOME / ".codex" / "config.toml"
    if env := os.getenv("CODEX_HOME"):
        path = Path(env).expanduser() / "config.toml"
    prefix = f"mcp_servers.{name}"
    lines = [
        f"[{prefix}]",
        f"command = {toml_str(uvx)}",
        f"args = {toml_str(server['args'])}",
        f"env = {toml_str(server['env'])}",
        # The first start downloads the server, which beats the 10s default.
        "startup_timeout_sec = 180",
        'default_tools_approval_mode = "prompt"',
    ]
    for tool in server["readOnlyTools"]:
        lines += ["", f"[{prefix}.tools.{tool}]", 'approval_mode = "approve"']
    old = path.read_text(encoding="utf-8") if path.exists() else ""
    try:
        tomllib.loads(old)
    except tomllib.TOMLDecodeError:
        sys.exit(f"ERROR: {path} isn't valid TOML, so it wasn't changed. "
                 "Fix or remove it, then re-run.")
    new = replace_toml_tables(old, prefix, "\n".join(lines) + "\n")
    tomllib.loads(new)  # never write a config Codex can't read
    plan.write(path, new)
    plan.next += [
        "Restart Codex so it loads the Garmin server: in the app, quit and "
        "reopen it; in the terminal, start a new codex session in this "
        "folder.",
        "In Codex the commands start with $: type $setup to continue, and "
        "later $checkin and $week.",
    ]


def cursor(plan: Plan, server: dict, uvx: str) -> None:
    copy_skills(plan, ROOT / ".cursor" / "skills")
    mcp = ROOT / ".cursor" / "mcp.json"
    plan.write(mcp, merge_server(mcp, "mcpServers", server["name"],
                                 stdio_entry(server, uvx)))
    plan.next += [
        "Quit and reopen Cursor with this folder, since it loads commands "
        "and servers at startup. If it asks to enable the "
        f"'{server['name']}' server, say yes.",
        "Cursor asks before each Garmin tool the first time; choosing to "
        "allow it is fine for the get_ tools, which only read.",
        "Type /setup in Agent chat to continue.",
    ]


def copilot(plan: Plan, server: dict, uvx: str) -> None:
    copy_skills(plan, ROOT / ".github" / "skills")
    home = Path(os.getenv("COPILOT_HOME", HOME / ".copilot")).expanduser()
    mcp = home / "mcp-config.json"
    entry = stdio_entry(server, uvx)
    entry["tools"] = ["*"]
    plan.write(mcp, merge_server(mcp, "mcpServers", server["name"], entry))
    plan.next += [
        "Reload VS Code (Command Palette, then 'Developer: Reload Window') "
        "and trust the Garmin server when asked.",
        "Use Copilot Chat in Agent mode. When it asks to run a Garmin "
        "get_ tool, 'Always allow' is fine for those; keep asking for "
        "anything that creates or deletes workouts.",
        "Type /setup in the chat to continue.",
    ]


def claude_desktop(plan: Plan, server: dict, uvx: str) -> None:
    if IS_WIN:
        base = Path(os.getenv("APPDATA", HOME)) / "Claude"
    else:
        base = HOME / "Library" / "Application Support" / "Claude"
    path = base / "claude_desktop_config.json"
    plan.write(path, merge_server(path, "mcpServers", server["name"],
                                  stdio_entry(server, uvx, typed=False)))
    plan.next += [
        "Fully quit Claude Desktop (not just close the window) and reopen "
        "it. Garmin then works in regular chats too.",
    ]


HARNESSES = {
    "claude-code": ("Claude Code (Claude Desktop's Code tab, or the CLI)",
                    claude_code),
    "cline": ("Cline (desktop app, VS Code extension, or CLI)", cline),
    "codex": ("OpenAI Codex (app, IDE extension, or CLI)", codex),
    "cursor": ("Cursor", cursor),
    "copilot": ("VS Code with GitHub Copilot (experimental)", copilot),
    "claude-desktop": ("Claude Desktop chats, Garmin connection only",
                       claude_desktop),
}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("harness", nargs="?", choices=sorted(HARNESSES))
    ap.add_argument("--list", action="store_true", help="list harnesses")
    ap.add_argument("--dry-run", action="store_true",
                    help="show what would change without writing")
    ap.add_argument("--uvx", help="full path to uvx, if it isn't found")
    args = ap.parse_args()

    if args.list or not args.harness:
        for key, (label, _) in HARNESSES.items():
            print(f"{key:15} {label}")
        return 0 if args.list else 2

    server = load_server()
    uvx = find_uvx(args.uvx)
    plan = Plan(args.dry_run)
    label, install = HARNESSES[args.harness]
    print(f"Setting up for {label}")
    install(plan, server, uvx)
    for step in plan.next:
        print(f"NEXT: {step}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
